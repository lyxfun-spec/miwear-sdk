"""Generate the deny-by-default Git selection from the reviewed public manifest."""
from pathlib import Path
import argparse

from prepare_public import selected_files

ROOT = Path(__file__).resolve().parents[1]


def expected_gitignore(root):
    names = selected_files(root)
    for name in names:
        if any(character in name for character in '*?[]!#\\\r\n'):
            raise ValueError('Unsupported literal Git path: ' + name)
    lines = ['# Generated by tools/sync_public.py from config/public-files.json.',
             '# Review every new public file before adding it to that manifest.', '*', '!*/']
    lines.extend('!/' + name for name in names)
    lines.extend(['', '/imports/', '/work/', '/outputs/', '/local-assets/',
                  '/local-private/', '__pycache__/', '*.py[cod]', ''])
    return '\n'.join(lines)


def check(root):
    if (root / '.gitignore').read_text(encoding='utf-8') != expected_gitignore(root):
        raise ValueError('Git selection is stale; run python tools/sync_public.py')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    if args.check:
        check(ROOT)
    else:
        (ROOT / '.gitignore').write_text(expected_gitignore(ROOT), encoding='utf-8', newline='\n')
    print('PASS: Git selection matches the reviewed manifest')


if __name__ == '__main__':
    main()
